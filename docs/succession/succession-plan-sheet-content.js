async function main() {
  const auth = new google.auth.OAuth2();
  auth.setCredentials({ access_token: process.env.ACCESS });
  const sheets = google.sheets({version: 'v4', auth});

  // Add all tabs
  const addReqs = TABS.map(t => ({ addSheet: { properties: { title: t.title } } }));
  await sheets.spreadsheets.batchUpdate({
    spreadsheetId: SPREADSHEET_ID,
    requestBody: { requests: addReqs },
  });
  console.log('Added ' + TABS.length + ' tabs');

  // Fill each tab
  for (const t of TABS) {
    const resp = await sheets.spreadsheets.values.update({
      spreadsheetId: SPREADSHEET_ID,
      range: `${t.title}!A1`,
      valueInputOption: 'USER_ENTERED',
      requestBody: { values: t.rows },
    });
    console.log(`Filled ${t.title}: ${resp.data.updatedCells} cells`);
  }

  // Format headers bold
  const formatReqs = TABS.map((t, i) => ({
    repeatCell: {
      range: { sheetId: i + 1, startRowIndex: 0, endRowIndex: 1 },
      cell: { userEnteredFormat: { textFormat: { bold: true }, backgroundColor: { red: 0.85, green: 0.9, blue: 1 } } },
      fields: 'userEnteredFormat.textFormat.bold,userEnteredFormat.backgroundColor',
    }
  }));
  await sheets.spreadsheets.batchUpdate({
    spreadsheetId: SPREADSHEET_ID,
    requestBody: { requests: formatReqs },
  });
  console.log('Header formatting done');
}
main().catch(e => { console.error(e.message || e); process.exit(1); });
